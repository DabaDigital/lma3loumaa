// Builds a single paste-ready supabase/setup.sql from migrations, review storage and seed.
// SQL is copied verbatim from the files exercised by both database test scripts.
// Usage: npm run db:setup -- you@example.com   (defaults to ADMIN_EMAIL, else a placeholder)
import { readFileSync, writeFileSync, readdirSync } from "node:fs";

const here = (path) => new URL(path, import.meta.url);
const read = (path) => readFileSync(here(path), "utf8").trimEnd();

const adminEmail =
  process.argv[2] || process.env.ADMIN_EMAIL || "YOUR_ADMIN_EMAIL";
if (
  !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(adminEmail) &&
  adminEmail !== "YOUR_ADMIN_EMAIL"
)
  throw new Error(`Not a valid email address: ${adminEmail}`);

const migrations = readdirSync(here("../supabase/migrations"))
  .filter((file) => file.endsWith(".sql"))
  .sort();

const banner = [
  "-- Lma3louma — one-time Supabase setup.",
  "-- Generated by `npm run db:setup`. Do not edit by hand; edit the migration or seed instead.",
  "--",
  "-- Paste this whole file into the Supabase SQL Editor and press Run, ONCE.",
  "-- It is not re-runnable: the schema section uses plain `create table` / `create function`,",
  '-- so a second run fails with "already exists". The seed section is safe to repeat.',
  "--",
  "-- Before running, create the admin's Auth user under Authentication -> Users -> Add user.",
  `-- The final statement grants dashboard access to: ${adminEmail}`,
  "",
].join("\n");

const section = (title) =>
  `\n\n-- ${"=".repeat(72)}\n-- ${title}\n-- ${"=".repeat(72)}\n\n`;

const grant = `insert into public.admin_users (user_id)
select id from auth.users where lower(email) = lower('${adminEmail.replaceAll("'", "''")}')
on conflict (user_id) do nothing;

-- Verify that exactly the intended account was granted membership.
-- An empty result means the Auth user does not exist yet: create it under
-- Authentication -> Users, then re-run just this section.
select u.email, a.created_at
from public.admin_users a join auth.users u on u.id = a.user_id;
`;

writeFileSync(
  here("../supabase/setup.sql"),
  banner +
    migrations
      .map(
        (file) =>
          section(`Schema — ${file}`) + read(`../supabase/migrations/${file}`),
      )
      .join("") +
    section("Review photos — review-storage.sql") +
    read("../supabase/review-storage.sql") +
    section("Protected reviews — review-protection.sql") +
    read("../supabase/review-protection.sql") +
    section("Content — seed.sql") +
    read("../supabase/seed.sql") +
    section("Admin access") +
    grant,
);

console.log(
  `Wrote supabase/setup.sql from ${migrations.length} migration(s) + review storage + seed, granting admin to ${adminEmail}.`,
);
